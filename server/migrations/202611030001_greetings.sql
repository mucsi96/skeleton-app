-- Adopt the existing Liquibase-managed table without changing rows, IDs, or
-- sequences. Seed only a new database, never an existing (even empty) table.
CREATE SCHEMA IF NOT EXISTS hello;
DO $$
BEGIN
    IF to_regclass('hello.greetings') IS NULL THEN
        CREATE TABLE hello.greetings (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            message TEXT NOT NULL
        );
        INSERT INTO hello.greetings (name, message)
        VALUES ('Igor', 'Welcome to the skeleton app!');
    END IF;
END
$$;
